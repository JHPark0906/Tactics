namespace HS.Framework.AI.Behaviour
{
    /// <summary>조건이 바뀌었을 때 무엇을 끊을지를 정한다.</summary>
    /// <remarks>
    /// 끊는다는 것은 실행 중인 가지를 처음으로 되돌린다는 뜻이며, 어디까지 되돌리는지는 범위가
    /// 정한다. 되돌려진 자리는 다음 실행에서 다시 고르므로 조건이 달라진 결과가 그 자리에서 반영된다.
    /// </remarks>
    public enum BehaviourAbortScope
    {
        /// <summary>끊지 않는다. 값이 바뀐 순간에는 아무것도 되돌리지 않고, 다음에 그 자리에 이를 때 조건을 본다.</summary>
        /// <remarks>그때 문이 닫히면 그 아래가 돌고 있었더라도 그 자리에서 되돌려진다. 문은 이를 때마다 보기 때문이다.</remarks>
        None,

        /// <summary>자기 아래가 실행 중일 때 그것을 끊는다.</summary>
        /// <remarks>
        /// 조건이 거짓이 되었는데 그 아래가 계속 도는 것을 막는다. 되돌리는 것은 <b>자기 아래뿐</b>이다.
        /// 부모와 형제의 진행은 그대로 두고, 다음 실행에서 이 자리가 실패를 돌려주면 부모가 그것을
        /// 보통의 실패로 다룬다.
        /// </remarks>
        Self,

        /// <summary>자기보다 뒤에 있는 형제가 실행 중일 때 그것을 끊는다.</summary>
        /// <remarks>
        /// 조건이 참이 되었으므로 자기 차례가 왔는데, 앞서 고르지 못해 뒤엣것이 돌고 있는 상황이다.
        /// 앞에 있는 자리가 곧 높은 우선순위이므로 <b>부모를 처음으로 되돌려</b> 그 자리를 되찾는다.
        /// </remarks>
        LowerPriority,

        /// <summary>둘 다 한다.</summary>
        Both
    }
}
