using UnityEngine;

namespace HS.Framework.Gameplay.Health
{
    /// <summary>
    /// 피해가 체력에 닿기 전에 그 일부나 전부를 대신 받아 가는 대상을 정의한다.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>왜 프레임워크에 있는가.</b> "피해는 가로채이거나 옮겨질 수 있다"는 것은 특정 게임의 규칙이 아니라
    /// 여러 게임이 되풀이해 쓰는 형태이다. 먼저 닳는 보호막, 일정 비율을 덜어 내는 장갑,
    /// 호위 대상 대신 맞아 주는 피해 전이가 모두 이 자리를 쓴다.
    /// 반면 <b>무엇이 왜 가로채는지는 게임의 것이다</b> — 프레임워크는 가로채는 이유를 알지 못한다.
    /// </para>
    /// <para>
    /// <b>가져간 양을 답한다.</b> 전부 가져가면 대상은 아무 피해도 받지 않고, 0을 답하면 지금까지와 똑같이
    /// 전부 체력에 들어간다. 일부만 가져가는 형태도 같은 계약으로 표현되므로,
    /// 나중에 부분 흡수가 필요해져도 계약을 다시 바꾸지 않아도 된다.
    /// </para>
    /// <para>
    /// <b>같은 오브젝트에 여럿 붙일 수 있다.</b> 붙은 차례대로 물으며 각자 <b>남은 양</b>을 본다.
    /// 보호막이 먼저 닳고 그다음 장갑이 덜어 내는 식의 층을 그대로 표현한다.
    /// 순서가 결과를 바꾸는 것은 층이라는 개념 자체의 성질이며, 차례는 컴포넌트가 붙은 차례로 정해져 있다.
    /// </para>
    /// <para>
    /// <b>여기서 체력을 건드리지 마라.</b> 이 호출은 피해가 적용되기 전에 일어나므로,
    /// 안에서 같은 대상의 체력을 다시 깎으면 알림 순서가 어긋난다.
    /// 가져간 피해를 다른 대상에게 넘기는 것은 괜찮다.
    /// </para>
    /// </remarks>
    public interface IDamageInterceptor
    {
        /// <summary>
        /// 이번 피해에서 얼마를 대신 받아 갈지 답한다.
        /// </summary>
        /// <param name="amount">아직 대상에게 닿지 않은 피해량이며 항상 1 이상이다.</param>
        /// <param name="instigator">피해를 발생시킨 GameObject이며, 알 수 없으면 null이다.</param>
        /// <returns>
        /// 대신 받아 갈 피해량이다. 0이면 가로채지 않는다.
        /// 0과 <paramref name="amount"/> 사이를 벗어난 값은 그 범위로 보정된다.
        /// </returns>
        int InterceptDamage(int amount, GameObject instigator);
    }
}
